"""Export representative NSGA-II designs as LTspice-compatible CMOS netlists.

The generated LEVEL=1 MOS models are illustrative models, not a foundry PDK.
Their KP values are estimated to match the Stage-1 effective resistance around
mid-supply. The netlists should be treated as a validation experiment, not as
sign-off simulations.
"""

from __future__ import annotations

import csv
import math
from pathlib import Path

from vlsi_model import (
    DEFAULT_CONFIG,
    DEFAULT_TECH,
    _device_dimensions,
    _output_diffusion_capacitance_fF,
    _gate_input_capacitance_fF,
)

ROOT = Path(__file__).resolve().parent
SUMMARY_CSV = ROOT / "outputs" / "design_summary.csv"
OUTPUT_DIR = ROOT / "ltspice_netlists"


def _read_designs(path: Path = SUMMARY_CSV) -> dict[str, tuple[float, float, float]]:
    if not path.exists():
        raise FileNotFoundError(
            f"Cannot find {path}. Run 'python optimize.py' before exporting netlists."
        )

    designs: dict[str, tuple[float, float, float]] = {}
    with path.open("r", newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        required = {"design", "x2_size_factor", "x3_size_factor", "x4_size_factor"}
        if not required.issubset(reader.fieldnames or set()):
            raise ValueError(
                f"{path.name} is missing required columns: {sorted(required)}"
            )
        for row in reader:
            name = row["design"].strip()
            if name in {"minimum_area", "balanced_compromise", "minimum_delay"}:
                sizes = tuple(
                    float(row[column])
                    for column in ("x2_size_factor", "x3_size_factor", "x4_size_factor")
                )
                if not all(math.isfinite(value) for value in sizes):
                    raise ValueError(f"Non-finite sizing values found for {name}")
                designs[name] = sizes  # type: ignore[assignment]

    missing = {"minimum_area", "balanced_compromise", "minimum_delay"} - designs.keys()
    if missing:
        raise ValueError(f"Missing representative designs in design_summary.csv: {sorted(missing)}")
    return designs


def _mid_swing_kp_a_per_v2(resistance_ohm: float, width_um: float) -> float:
    """Estimate LEVEL=1 KP using the long-channel triode equation at VDS=VDD/2."""
    vdd = DEFAULT_TECH.supply_voltage_v
    vth = DEFAULT_TECH.threshold_voltage_n_v
    vds_mid = vdd / 2.0
    vov = vdd - vth
    triode_factor_v = vov - vds_mid / 2.0
    if resistance_ohm <= 0 or width_um <= 0 or triode_factor_v <= 0:
        raise ValueError("Invalid values for estimating MOS model KP")
    w_over_l = width_um / DEFAULT_TECH.channel_length_um
    return 1.0 / (resistance_ohm * w_over_l * triode_factor_v)


def _spice_number(value: float) -> str:
    return f"{value:.9g}"


def render_netlist(design_name: str, variable_sizes: tuple[float, float, float]) -> str:
    cfg = DEFAULT_CONFIG
    tech = DEFAULT_TECH
    sizes = (cfg.fixed_first_stage_size, *variable_sizes)

    if len(sizes) != cfg.n_stages:
        raise ValueError(f"Expected {cfg.n_stages} total inverter sizes")
    if any(not (cfg.min_size <= x <= cfg.max_size) for x in variable_sizes):
        raise ValueError(
            f"Sizing factors must be within [{cfg.min_size}, {cfg.max_size}]"
        )

    wn_min = tech.min_nmos_width_um
    wp_min = wn_min * tech.pmos_to_nmos_width_ratio
    r_p_at_configured_width = tech.r_p_min_ohm / tech.pmos_to_nmos_width_ratio
    kp_n = _mid_swing_kp_a_per_v2(tech.r_n_min_ohm, wn_min)
    kp_p = _mid_swing_kp_a_per_v2(r_p_at_configured_width, wp_min)

    min_inv_input_cap_ff = _gate_input_capacitance_fF(1.0, tech)
    external_load_ff = cfg.external_load_multiplier * min_inv_input_cap_ff

    lines: list[str] = [
        f"{design_name.replace('_', ' ').title()} - four-stage CMOS inverter chain",
        "* AUTO-GENERATED by export_ltspice.py",
        "* Educational LEVEL=1 MOS models; NOT a foundry PDK or sign-off model.",
        "* KP is estimated from the Stage-1 effective R around Vout = VDD/2.",
        "* Explicit Cpar elements represent the Stage-1 output diffusion + wire capacitance.",
        "",
        f".param VDD={_spice_number(tech.supply_voltage_v)}",
        f".param LCH={_spice_number(tech.channel_length_um)}u",
        "VDD_SRC vdd 0 {VDD}",
        "VIN in 0 PULSE(0 {VDD} 1n 20p 20p 5n 10n)",
        "",
    ]

    previous_node = "in"
    for index, size in enumerate(sizes, start=1):
        output_node = "out" if index == cfg.n_stages else f"n{index}"
        wn, wp = _device_dimensions(size, tech)
        w_n_text = f"{_spice_number(wn)}u"
        w_p_text = f"{_spice_number(wp)}u"

        lines.extend([
            f"M{index}N {output_node} {previous_node} 0 0 NMOD W={w_n_text} L={{LCH}}",
            f"M{index}P {output_node} {previous_node} vdd vdd PMOD W={w_p_text} L={{LCH}}",
        ])

        diffusion_ff = _output_diffusion_capacitance_fF(size, tech)
        wire_ff = cfg.interconnect_capacitance_fF_per_stage
        lines.append(
            f"CDIFF{index} {output_node} 0 {_spice_number(diffusion_ff)}f"
        )
        lines.append(f"CWIRE{index} {output_node} 0 {_spice_number(wire_ff)}f")
        lines.append("")
        previous_node = output_node

    lines.extend([
        f"CLOAD out 0 {_spice_number(external_load_ff)}f",
        "",
        "* LEVEL=1 long-channel MOS models; KP values are illustrative estimates.",
        f".model NMOD NMOS (LEVEL=1 VTO={_spice_number(tech.threshold_voltage_n_v)} "
        f"KP={_spice_number(kp_n)} LAMBDA=0 GAMMA=0.4 PHI=0.7 TOX=5n "
        "CGSO=75p CGDO=75p)",
        f".model PMOD PMOS (LEVEL=1 VTO=-{_spice_number(tech.threshold_voltage_p_abs_v)} "
        f"KP={_spice_number(kp_p)} LAMBDA=0 GAMMA=0.4 PHI=0.7 TOX=5n "
        "CGSO=75p CGDO=75p)",
        "",
        f".temp {tech.temperature_c:.6g}",
        ".options plotwinsize=0 reltol=1e-4 abstol=1e-15 vntol=1e-6",
        ".save V(in) V(n1) V(n2) V(n3) V(out)",
        ".tran 0 25n 0 2p",
        "",
        "* Four inverters give non-inverting overall polarity.",
        "* Measure propagation delay from input 50% crossing to output 50% crossing.",
        ".meas TRAN tplh TRIG V(in) VAL={VDD/2} RISE=1 TARG V(out) VAL={VDD/2} RISE=1",
        ".meas TRAN tphl TRIG V(in) VAL={VDD/2} FALL=1 TARG V(out) VAL={VDD/2} FALL=1",
        ".meas TRAN tpd_avg PARAM (tplh+tphl)/2",
        "",
        ".end",
        "",
        "* Stage sizing factors: " + ", ".join(f"{x:.9g}" for x in sizes),
        "* Python model external load: " + f"{external_load_ff:.9g} fF",
        "* Approximate mid-swing KP_N/KP_P: " + f"{kp_n:.9g} / {kp_p:.9g} A/V^2",
    ])
    return "\n".join(lines)


def main() -> None:
    designs = _read_designs()
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    for name, sizes in designs.items():
        target = OUTPUT_DIR / f"{name}.cir"
        target.write_text(render_netlist(name, sizes), encoding="utf-8")
        print(f"Created: {target.relative_to(ROOT)}")

    # Create a data-entry template prefilled with Python-model values.
    template_path = OUTPUT_DIR / "ltspice_measurements_template.csv"
    with SUMMARY_CSV.open("r", newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        summary_rows = {row["design"].strip(): row for row in reader}
    with template_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow([
            "design", "x2_size_factor", "x3_size_factor", "x4_size_factor",
            "python_area_um2", "python_estimated_delay_ns",
            "ltspice_tplh_ns", "ltspice_tphl_ns", "ltspice_tpd_avg_ns",
            "absolute_error_percent", "notes"
        ])
        for name in ("minimum_area", "balanced_compromise", "minimum_delay"):
            row = summary_rows[name]
            writer.writerow([
                name, row["x2_size_factor"], row["x3_size_factor"],
                row["x4_size_factor"], row["transistor_channel_area_um2"],
                row["estimated_delay_ns"], "", "", "", "", ""
            ])

    # Copy a small metadata file alongside the generated netlists.
    metadata = OUTPUT_DIR / "README.txt"
    metadata.write_text(
        "LTspice Stage 2 netlists\n"
        "========================\n\n"
        "Open each .cir file in LTspice and click Run.\n"
        "Open View > SPICE Error Log (Ctrl+L) after simulation to read tplh, tphl,\n"
        "and tpd_avg measurements.\n\n"
        "These are illustrative LEVEL=1 MOS models, not a foundry PDK. The KP\n"
        "values are estimated to roughly match the Stage-1 effective resistance\n"
        "around mid-supply. Differences between Python and LTspice are expected\n"
        "because the transistor-level model has nonlinear I-V behaviour and\n"
        "additional model assumptions.\n",
        encoding="utf-8",
    )
    print(f"\nNetlists exported to: {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
